#!/usr/bin/env node
/**
 * file-budget.mjs — the file token budget guard (OPT-IN pre-commit hook).
 *
 * Blocks any staged file whose size exceeds a token budget, using the coarse
 * estimator tokens ~= bytes/4. Rationale: agent-authored files grow silently;
 * a file that reads in one sitting keeps both the agent and the human
 * effective. The block message carries the split instructions — the message
 * IS the feature, not an afterthought.
 *
 * Style enforcement, deliberately NOT the evidence veto: it must stay cheap,
 * stay quiet on success, and never run unless the adopter wires it in:
 *
 *   # in the adopter repo (core.hooksPath already set by setup-tna):
 *   node /path/to/file-budget.mjs          # or copied beside the hook
 *
 * CLI contract (the public seam; see file-budget.test.mjs):
 *   exit 0   every staged file within budget (or ignorable), nothing staged,
 *            or run outside a git repo (fail-open on its own environment)
 *   exit 1   at least one staged file over budget (block), or bad --limit
 *   --all    audit every indexed file, not just the staged delta
 *   --limit=N  override the default 5,000-token budget
 *
 * Ignored by default: lockfiles, maps/minified bundles, and common generated
 * directories — machine-generated content is not agent-authored prose. A
 * repo can ignore more via `.filebudgetignore` at its root (one exact path
 * or `dir/` prefix per line), and binary content is skipped by sniffing.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const DEFAULT_LIMIT = 5000;
const BYTES_PER_TOKEN = 4;

// Basenames that are machine-generated by toolchains, never authored prose.
const FILE_IGNORES = new Set([
  'package-lock.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb', 'bun.lock',
  'composer.lock', 'Cargo.lock', 'poetry.lock', 'Gemfile.lock', 'npm-shrinkwrap.json',
  'CHANGELOG.md', // append-only release history grows by design
]);

// Directory segments that hold generated or vendored content.
const DIR_IGNORES = new Set(['node_modules', 'vendor', 'dist', 'build', '.git', 'coverage']);

const isBinary = (buf) => {
  const head = buf.subarray(0, 8192);
  if (head.includes(0)) return true; // NUL byte: the classic binary tell
  const s = head.toString('utf8');
  let bad = 0;
  for (const ch of s) if (ch === '\uFFFD') bad++;
  return bad / Math.max(s.length, 1) > 0.01; // replacement-char ratio
};

const ignored = (rel) => {
  const segs = rel.split('/');
  const base = segs[segs.length - 1];
  if (segs.some((s) => DIR_IGNORES.has(s))) return true;
  if (FILE_IGNORES.has(base)) return true;
  if (/\.(min\.js|min\.css|map)$/.test(base)) return true;
  return false;
};

/** Parse .filebudgetignore at the repo root: exact paths or `dir/` prefixes. */
const readIgnoreFile = (root) => {
  const p = join(root, '.filebudgetignore');
  if (!existsSync(p)) return { exact: new Set(), prefixes: [] };
  const exact = new Set();
  const prefixes = [];
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const e = line.trim();
    if (!e || e.startsWith('#')) continue;
    if (e.endsWith('/')) prefixes.push(e);
    else exact.add(e);
  }
  return { exact, prefixes };
};

const matchesIgnore = (rel, ig) =>
  ig.exact.has(rel) || ig.prefixes.some((pre) => rel.startsWith(pre));

const main = () => {
  const args = process.argv.slice(2);
  let limit = DEFAULT_LIMIT;
  let all = false;
  for (const a of args) {
    if (a === '--all') all = true;
    else if (a.startsWith('--limit=')) {
      const n = Number(a.slice('--limit='.length));
      if (!Number.isInteger(n) || n <= 0) {
        process.stderr.write(`file-budget: invalid --limit "${a.slice('--limit='.length)}" — use a positive integer\n`);
        process.exit(1);
      }
      limit = n;
    }
  }

  // Repo root: hooks run at top-level, but be explicit. Outside a repo = nothing to judge (fail-open).
  let root;
  try { root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim(); }
  catch { return; }
  const git = (a) => execFileSync('git', a, { cwd: root, encoding: 'utf8' });

  // Staged delta only (Added/Copied/Modified — deletions judge nothing).
  const list = all
    ? git(['ls-files']).split('\n')
    : git(['diff', '--cached', '--name-only', '--diff-filter=ACM']).split('\n');
  const rels = list.map((s) => s.trim()).filter(Boolean);
  if (rels.length === 0) return;

  const ig = readIgnoreFile(root);
  const offenders = [];
  for (const rel of rels) {
    if (ignored(rel) || matchesIgnore(rel, ig)) continue;
    const abs = join(root, ...rel.split('/'));
    let size;
    try { size = statSync(abs).size; } catch { continue; } // deleted between stage and run
    const tokens = Math.round(size / BYTES_PER_TOKEN);
    if (tokens <= limit) continue;
    let buf;
    try { buf = readFileSync(abs); } catch { continue; }
    if (isBinary(buf)) continue;
    offenders.push({ rel, tokens, limit });
  }

  if (offenders.length === 0) return;
  for (const o of offenders) {
    process.stdout.write(`file-budget: ${o.rel} is ~${o.tokens} tokens (limit ${o.limit})\n`);
  }
  process.stdout.write(`
Split it before committing:
  - extract one cohesive concern into its own module and import what moved
  - data tables and fixtures belong in a data file beside the code, not inline
  - generated content belongs in a build step, never in source

Legitimately large file? Ignore it for this repo: add its path (or a
dir/ prefix) to .filebudgetignore at the repo root, one per line — or
raise the budget for one run: node file-budget.mjs --limit=6000
`);
  process.exit(1);
};

main();
